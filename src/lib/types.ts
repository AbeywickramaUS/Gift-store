// ============================================
// Gift Store — Global Type Definitions
// ============================================

/** Product category types */
export type ProductCategory = 
  | 'skincare'
  | 'accessories';

/** Sub-categories for more granular filtering */
export type ProductSubCategory =
  | 'sheet-masks'
  | 'eye-masks'
  | 'lip-masks'
  | 'sleeping-masks'
  | 'foot-masks'
  | 'facial-razors'
  | 'necklaces'
  | 'earrings'
  | 'hair-clips'
  | 'everyday-essentials';

/** Package category for curated gift sets */
export type PackageCategory =
  | 'skincare-sets'
  | 'birthday-gifts'
  | 'anniversary-gifts'
  | 'everyday-essentials';

/** Media item — supports both Supabase-hosted and external URLs */
export interface MediaItem {
  type: 'image' | 'video';
  /** Full URL — either Supabase Storage public URL or external (YouTube/Cloudinary/Instagram) */
  url: string;
  /** 'supabase' | 'youtube' | 'cloudinary' | 'instagram' | 'external' */
  source: 'supabase' | 'youtube' | 'cloudinary' | 'instagram' | 'external';
  /** Alt text for images, title for videos */
  alt?: string;
  /** Thumbnail URL for video previews */
  thumbnail?: string;
}

/** Product stored in Supabase */
export interface Product {
  id: string;
  name: string;
  slug: string;
  description: string;
  price: number; // in LKR
  category: ProductCategory;
  sub_category: ProductSubCategory;
  /** JSONB — array of media items (images + videos) */
  media: MediaItem[];
  stock_quantity: number;
  /** Generated column: stock_quantity > 0 (read-only) */
  in_stock: boolean;
  /** Packed weight, used for the delivery fee */
  weight_grams: number;
  featured: boolean;
  /** false = hidden from the shop (anon users can't see it) */
  is_active: boolean;
  created_at: string;
  updated_at: string;
}

/** Curated gift package */
export interface Package {
  id: string;
  name: string;
  slug: string;
  description: string;
  price: number; // in LKR
  category: PackageCategory;
  /** JSONB — array of product IDs included */
  product_ids: string[];
  /** JSONB — media for the package itself */
  media: MediaItem[];
  stock_quantity: number;
  /** Generated column: stock_quantity > 0 (read-only) */
  in_stock: boolean;
  /** Packed weight (items + box), used for the delivery fee */
  weight_grams: number;
  featured: boolean;
  is_active: boolean;
  created_at: string;
  updated_at: string;
}

/** Custom box item selected by customer */
export interface CustomBoxItem {
  product_id: string;
  product_name: string;
  quantity: number;
  unit_price: number; // LKR
}

/** Items of a curated (package) order */
export interface CuratedOrderItems {
  package_id: string;
  package_name: string;
}

/** One line of a WhatsApp-checkout (cart) order, priced by the database */
export interface CartOrderLine {
  type: 'product' | 'package';
  id: string;
  slug: string;
  name: string;
  quantity: number;
  unit_price: number;
  line_total: number;
  weight_grams: number;
}

export type OrderStatus = 'pending' | 'confirmed' | 'shipped' | 'delivered' | 'cancelled';

/** No COD — every order starts as awaiting_payment */
export type PaymentStatus = 'awaiting_payment' | 'paid' | 'refunded';

interface OrderBase {
  id: string;
  /** Human-readable reference, generated by the DB, e.g. GIFT-1001 */
  order_ref: string;
  /** Customer & delivery info */
  customer_name: string;
  /** 07XXXXXXXX or +947XXXXXXXX (checked by the DB) */
  customer_phone: string;
  /** Defaults to customer_phone */
  customer_whatsapp: string | null;
  customer_email: string | null;
  customer_address: string;
  customer_city: string;
  customer_district: string;
  gift_note: string | null;
  /** Money in LKR. total_lkr is generated: subtotal + delivery fee */
  subtotal_lkr: number;
  delivery_fee_lkr: number;
  total_lkr: number;
  total_weight_grams: number | null;
  payment_status: PaymentStatus;
  status: OrderStatus;
  admin_notes: string | null;
  created_at: string;
  updated_at: string;
}

/** Order stored in Supabase — discriminated on order_type */
export type Order =
  | (OrderBase & { order_type: 'curated'; items: CuratedOrderItems; box_style: null })
  | (OrderBase & { order_type: 'custom'; items: CustomBoxItem[]; box_style: string | null })
  | (OrderBase & { order_type: 'cart'; items: CartOrderLine[]; box_style: null });

/** Dev blog entry for the /dev-blog page */
export interface DevLogEntry {
  step: number;
  title: string;
  date: string;
  filesChanged: string[];
  description: string;
  stateAndChallenges: string;
}
